"""Generate board PNGs into img/ (called once at game start).

You usually do not edit this file to learn the game logic —
start with roll.py → tower.py → game.py instead.
"""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

IMG = Path(__file__).resolve().parent / "img"
SIZE = 64

# Material palettes: base, highlight, shadow, text
MAT = {
    "toothpicks": ((196, 168, 120), (220, 198, 150), (140, 110, 70), (40, 30, 20)),
    "rotten_wood": ((92, 74, 48), (120, 98, 62), (50, 38, 24), (230, 220, 200)),
    "wood": ((160, 110, 58), (190, 140, 80), (100, 70, 35), (255, 245, 230)),
    "brick": ((168, 72, 58), (200, 100, 80), (110, 40, 35), (255, 240, 230)),
    "steel": ((140, 150, 162), (190, 200, 210), (70, 80, 90), (20, 24, 30)),
    "concrete": ((110, 112, 118), (150, 152, 158), (60, 62, 68), (240, 240, 245)),
}


def _font(size=14, bold=False):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    ]
    for path in candidates:
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def _rounded(draw, box, radius, fill, outline=None, width=1):
    draw.rounded_rectangle(box, radius=radius, fill=fill, outline=outline, width=width)


def _save(img, name):
    IMG.mkdir(exist_ok=True)
    img.save(IMG / f"{name}.png")


def make_material(name):
    base, hi, sh, fg = MAT[name]
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (2, 10, SIZE - 3, SIZE - 8), 6, fill=base, outline=sh, width=2)
    # slab highlight stripe
    d.rectangle((6, 14, SIZE - 7, 20), fill=hi)
    # grain / brick lines
    if name == "brick":
        for y in (28, 40, 50):
            d.line((8, y, SIZE - 9, y), fill=sh, width=1)
        d.line((SIZE // 2, 20, SIZE // 2, SIZE - 12), fill=sh, width=1)
    elif name in ("wood", "rotten_wood", "toothpicks"):
        for x in range(10, SIZE - 8, 6):
            d.line((x, 22, x + 2, SIZE - 12), fill=sh, width=1)
    elif name == "steel":
        d.rectangle((8, 26, SIZE - 9, 34), fill=hi)
        d.rectangle((8, 40, SIZE - 9, 46), fill=sh)
    else:  # concrete
        for _ in range(8):
            pass
        d.point([(12, 30), (40, 36), (22, 48), (48, 28)], fill=sh)
    # label
    font = _font(11, bold=True)
    label = {"toothpicks": "PICK", "rotten_wood": "ROTT", "wood": "WOOD",
             "brick": "BRCK", "steel": "STEL", "concrete": "CONC"}[name]
    d.text((SIZE // 2, SIZE - 18), label, font=font, fill=fg, anchor="mm")
    _save(img, name)


def make_floor_variant(name, height, status):
    """status: ok | warn | fail"""
    base, hi, sh, fg = MAT[name]
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    border = {"ok": sh, "warn": (220, 160, 40), "fail": (220, 50, 50)}[status]
    _rounded(d, (2, 8, SIZE - 3, SIZE - 6), 6, fill=base, outline=border, width=3)
    d.rectangle((6, 12, SIZE - 7, 18), fill=hi)
    font = _font(16, bold=True)
    d.text((SIZE // 2, SIZE // 2 + 4), f"{height}m", font=font, fill=fg, anchor="mm")
    key = f"fl_{name}_{height}_{status}"
    _save(img, key)
    return key


def make_button(name, fill, label):
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    sh = tuple(max(0, c - 40) for c in fill)
    hi = tuple(min(255, c + 35) for c in fill)
    _rounded(d, (3, 8, SIZE - 4, SIZE - 8), 12, fill=fill, outline=sh, width=2)
    d.arc((8, 12, SIZE - 9, 28), 200, 340, fill=hi, width=2)
    font = _font(13, bold=True)
    d.text((SIZE // 2, SIZE // 2 + 2), label, font=font, fill=(255, 255, 255), anchor="mm")
    _save(img, name)


def make_chip(name, fill, label, fg=(255, 255, 255)):
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (4, 14, SIZE - 5, SIZE - 14), 10, fill=fill)
    font = _font(12, bold=True)
    d.text((SIZE // 2, SIZE // 2), label, font=font, fill=fg, anchor="mm")
    _save(img, name)


def make_slot_top():
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (4, 10, SIZE - 5, SIZE - 10), 8, fill=(40, 90, 70), outline=(80, 220, 150), width=2)
    font = _font(12, bold=True)
    d.text((SIZE // 2, SIZE // 2), "TOP", font=font, fill=(180, 255, 210), anchor="mm")
    _save(img, "slot_top")


def make_ground():
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rectangle((0, 28, SIZE, SIZE), fill=(55, 48, 40))
    d.rectangle((0, 28, SIZE, 34), fill=(90, 160, 80))
    for x in range(0, SIZE, 8):
        d.line((x, 36, x + 4, SIZE), fill=(40, 35, 30), width=1)
    _save(img, "ground")


def make_bg():
    w, h = 640, 900
    img = Image.new("RGB", (w, h), (18, 24, 38))
    d = ImageDraw.Draw(img)
    for y in range(h):
        t = y / h
        r = int(18 + 20 * t)
        g = int(24 + 30 * t)
        b = int(38 + 50 * t)
        d.line((0, y, w, y), fill=(r, g, b))
    # faint skyline silhouettes
    for x0, bw, bh in [(40, 50, 180), (120, 70, 260), (220, 40, 140), (300, 90, 320),
                       (420, 55, 200), (500, 75, 280), (580, 45, 160)]:
        top = h - bh - 80
        d.rectangle((x0, top, x0 + bw, h - 60), fill=(12, 16, 26))
        for wy in range(top + 10, h - 70, 18):
            for wx in range(x0 + 8, x0 + bw - 6, 14):
                if (wx + wy) % 28 < 14:
                    d.rectangle((wx, wy, wx + 6, wy + 8), fill=(40, 50, 70))
    _save(img, "bg")


def make_challenge_icon():
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (6, 6, SIZE - 7, SIZE - 7), 10, fill=(140, 40, 40), outline=(220, 80, 80), width=2)
    font = _font(20, bold=True)
    d.text((SIZE // 2, SIZE // 2), "!", font=font, fill=(255, 220, 180), anchor="mm")
    _save(img, "challenge")


def height_chip(meters: int, accent=(90, 140, 200)):
    """Compact height readout chip; returns img key."""
    meters = int(meters)
    key = f"ht_{meters}"
    path = IMG / f"{key}.png"
    if path.exists():
        return key
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (2, 16, SIZE - 3, SIZE - 16), 8, fill=(28, 36, 52), outline=accent, width=2)
    font = _font(14, bold=True)
    d.text((SIZE // 2, SIZE // 2), f"{meters}m", font=font, fill=(230, 236, 245), anchor="mm")
    _save(img, key)
    return key


def rolls_chip(n: int):
    key = f"rolls_{n}"
    path = IMG / f"{key}.png"
    if path.exists():
        return key
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (6, 14, SIZE - 7, SIZE - 14), 10, fill=(36, 48, 70), outline=(100, 130, 180), width=2)
    font = _font(13, bold=True)
    d.text((SIZE // 2, SIZE // 2), f"x{n}", font=font, fill=(210, 225, 255), anchor="mm")
    _save(img, key)
    return key


def make_arrow():
    """Placement cursor — bright arrow pointing at insert row."""
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # glow circle
    d.ellipse((8, 8, SIZE - 9, SIZE - 9), fill=(30, 80, 50), outline=(100, 255, 160), width=3)
    # arrow pointing right into the tower
    d.polygon(
        [(14, SIZE // 2), (34, 18), (34, 28), (50, 28), (50, 36), (34, 36), (34, SIZE - 18)],
        fill=(180, 255, 200),
    )
    _save(img, "arrow")


def make_insert_ghost():
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    _rounded(d, (4, 10, SIZE - 5, SIZE - 10), 8, fill=(40, 100, 80), outline=(120, 255, 180), width=2)
    font = _font(11, bold=True)
    d.text((SIZE // 2, SIZE // 2), "HERE", font=font, fill=(200, 255, 220), anchor="mm")
    _save(img, "insert_here")


def ensure_assets():
    """Create/refresh all static assets."""
    for name in MAT:
        make_material(name)
    make_button("btn_roll", (46, 125, 90), "ROLL")
    make_button("btn_scrap", (140, 70, 60), "SCRAP")
    make_chip("badge_p1", (50, 110, 190), "P1")
    make_chip("badge_p2", (190, 110, 50), "P2")
    make_chip("badge_you", (220, 180, 50), "YOU", fg=(30, 25, 10))
    make_chip("badge_goal", (60, 70, 100), "150m")
    make_slot_top()
    make_ground()
    make_bg()
    make_challenge_icon()
    make_arrow()
    make_insert_ghost()
    Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0)).save(IMG / "empty.png")
    for n in range(0, 4):
        rolls_chip(n)
    return True


_FLOOR_CACHE = {}


def floor_image(material: str, height: int, status: str = "ok") -> str:
    """Return img key for a floor tile (cached on disk)."""
    key = f"fl_{material}_{int(height)}_{status}"
    if key not in _FLOOR_CACHE:
        path = IMG / f"{key}.png"
        if not path.exists():
            make_floor_variant(material, int(height), status)
        _FLOOR_CACHE[key] = key
    return key


if __name__ == "__main__":
    ensure_assets()
    print("assets written to", IMG)
